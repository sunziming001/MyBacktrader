"""板块判定。

**板块**（主板 / 创业板 / 科创板 / 北交所）回答「适用哪套交易制度」，与**品种**
（股票 / 指数 / 可转债 / 基金）不在同一层。CONTEXT.md 中「品种」的 _Avoid_ 明确列了
「板块」，二者不可混用。

判定依据有两段信息，都来自文件名形式的符号：市场前缀给出交易所（``sh`` / ``sz`` / ``bj``），
代码前缀给出该交易所内的分段。用市场前缀而非仅代码前缀，是因为它直接可读且无歧义。

判不出板块时**报错**而不兜底：把指数或可转债硬套一个板块，会让规则取值悄悄失真
（ADR-0004 要求非股票标的不得进入股票池）。
"""

from __future__ import annotations

from .errors import RuleTableError

#: 市场前缀 + 代码前缀 → 板块。代码前缀按最长匹配取值。
_BOARD_RULES = {
    "sh": (
        ("688", "科创板"),
        ("689", "科创板"),
        ("600", "沪主板"),
        ("601", "沪主板"),
        ("603", "沪主板"),
        ("605", "沪主板"),
    ),
    "sz": (
        ("300", "创业板"),
        ("301", "创业板"),
        ("000", "深主板"),
        ("001", "深主板"),
        ("002", "深主板"),
        ("003", "深主板"),
    ),
}

#: 北交所的代码前缀在价格与财务数据中均为 920，另有新三板转板前的历史段。
_BJ_PREFIXES = (
    "920",
    "430",
    "830",
    "831",
    "832",
    "833",
    "834",
    "835",
    "836",
    "837",
    "838",
    "839",
    "870",
    "871",
    "872",
    "873",
    "874",
    "875",
)


def board_of(symbol: str) -> str:
    """由符号判定板块。判不出时报错，不猜。"""
    market, code = symbol[:2], symbol[2:]

    if market == "bj":
        if code.startswith(_BJ_PREFIXES):
            return "北交所"
    else:
        for prefix, board in _BOARD_RULES.get(market, ()):
            if code.startswith(prefix):
                return board

    raise RuleTableError(
        f"无法由符号 {symbol!r} 判定板块：它可能是指数、可转债或基金，"
        f"这类标的没有板块，不得套用股票的交易制度"
    )
