"""品种判定：由代码前缀回答「这是什么」。

**品种**（股票 / 指数 / 可转债 / 基金 / 其他）与**板块**（主板 / 创业板 / 科创板 / 北交所）
不在同一层：品种答「这是什么」，板块答「它适用哪套规则」。`CONTEXT.md` 中「品种」的
_Avoid_ 明确列了「板块」，二者不可混用——指数**有**品种而无板块，把两件事合并就会被迫
给指数编一个板块。

判定需要**市场前缀 + 代码前缀**两段信息，缺一不可：指数与股票共用 ``000`` / ``300`` 这类
数字，``sh000001`` 是上证指数而 ``sz000001`` 是平安银行，只按代码前缀判必错一个。

判不出时归入**「其他」而不报错**。这与 :func:`mbt.rules.board_of` 的报错刻意不对称：

- 板块判错的后果是**规则取值失真**（错得无声），所以它必须报错；
- 品种归入「其他」的后果只是该标的**不被股票池收**，错在**不收**这个安全方向（fail-closed）。

真实目录里一定混着 B 股、国债逆回购、企业债之类，让一次全市场扫描因一个陌生前缀整体
失败，比少收几只更糟。

判定与规则层的板块判定是**两份独立的知识**，可能漂移；`tests/test_instrument.py` 有一条
交叉检查把它们重叠的部分钉住。
"""

from __future__ import annotations

#: 股票。科创板 ``688`` / ``689`` 与创业板 ``300`` / ``301`` 都是股票，
#: 它们的板块不同但品种相同。
_STOCK_PREFIXES = {
    "sh": ("600", "601", "603", "605", "688", "689"),
    "sz": ("000", "001", "002", "003", "300", "301"),
    # 北交所：920 为现行代码段，其余为转板前的新三板段
    "bj": (
        "920",
        "430",
        "830",
        "831",
        "832",
        "833",
        "834",
        "835",
        "836",
        "837",
        "838",
        "839",
        "870",
        "871",
        "872",
        "873",
        "874",
        "875",
    ),
}

#: 指数。沪市指数在 ``000`` 段，深市指数在 ``399`` 段。
_INDEX_PREFIXES = {
    "sh": ("000",),
    "sz": ("399",),
}

#: 可转债。沪市 ``110`` / ``111`` / ``113`` / ``118``，深市 ``123`` / ``127`` / ``128``。
_BOND_PREFIXES = {
    "sh": ("110", "111", "113", "118"),
    "sz": ("123", "127", "128"),
}

#: 基金。含 ETF、LOF 与公募 REITs；``588``（科创板 ETF）与股票的 ``688`` 只差一位。
_FUND_PREFIXES = {
    "sh": ("50", "51", "52", "53", "55", "56", "58"),
    "sz": ("15", "16", "17"),
}

#: 品种的取值。顺序即判定的**优先级**：同一代码段重叠时靠前的先命中。
_TYPES_BY_PREFIX = (
    ("股票", _STOCK_PREFIXES),
    ("指数", _INDEX_PREFIXES),
    ("可转债", _BOND_PREFIXES),
    ("基金", _FUND_PREFIXES),
)

#: 判不出时的品种。它不是「兜底垃圾桶」，而是「已知不属于以上四类或前缀未知」。
OTHER = "其他"


def instrument_type(symbol: str) -> str:
    """由符号判定品种，判不出时返回 :data:`OTHER`（**不抛错**）。

    参数:
        symbol: 标的符号，形如 ``sh600000``（市场前缀 + 代码）。
    """
    if len(symbol) < 3:
        return OTHER

    market, code = symbol[:2], symbol[2:]
    for name, prefixes_by_market in _TYPES_BY_PREFIX:
        if code.startswith(prefixes_by_market.get(market, ())):
            return name

    return OTHER


def is_stock(symbol: str) -> bool:
    """该标的是否为股票——股票池只从判为股票的品种中构建（ADR-0004）。"""
    return instrument_type(symbol) == "股票"


def bare_code(symbol: str) -> str:
    """取 6 位裸代码：``sh600000`` → ``600000``；已经是裸代码的原样返回。

    通达信自己那几处文件格式只认裸代码——按期财报（``gpcw``）、证券主表 ``base.dbf``、
    以及导出的自选股 ``.EBK``。它是**符号的两种写法**之间的转换，不是品种判定。

    **不校验市场前缀与代码是否匹配**：``sh000001`` 是上证指数、``sz000001`` 是平安银行，
    两者都是合法的（市场, 代码）组合，去掉市场段之后都是 ``000001``。那件校验是
    :func:`instrument_type` 的事。

    **判不出时不报错**（短于 7 个字符就原样返回）：调用方拿到的可能是已经裸着的代码，
    替它报错只会逼每个调用方先自己判一次长度。
    """
    return symbol[2:] if len(symbol) > 6 else symbol
